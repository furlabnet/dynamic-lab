#!/usr/bin/env node
/**
 * Second half of the build, after tsc has compiled src/ into dist/:
 * - compresses every fonts/*.otf into dist/fonts/*.woff2
 * - writes dist/the-lab-sans.css with one @font-face per face, plus the --font-the-lab-sans variable
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { compress } from 'wawoff2'
import { cssVariable, faces, fontFamily, fontStack } from '../dist/index.js'

const root = new URL('../', import.meta.url)
const fontsOut = new URL('dist/fonts/', root)
await mkdir(fontsOut, { recursive: true })

// One at a time: compress() returns a view into WebAssembly memory that the next call can move,
// so each result is copied out before the next file starts.
for (const { file } of faces) {
  const otf = await readFile(new URL(`fonts/${file}.otf`, root))
  await writeFile(new URL(`${file}.woff2`, fontsOut), Buffer.from(await compress(otf)))
}

const rules = faces.map(
  ({ file, weight, style }) => `@font-face {
  font-family: '${fontFamily}';
  src: url('./fonts/${file}.woff2') format('woff2');
  font-weight: ${weight};
  font-style: ${style};
  font-display: swap;
}`
)

const css = `/* ${fontFamily}: @furlab/the-lab-sans. Generated by scripts/build-css.mjs; don't edit. */
${rules.join('\n')}
:root {
  ${cssVariable}: ${fontStack};
}
`
await writeFile(new URL('dist/the-lab-sans.css', root), css)
console.log(`✔ ${faces.length} faces → dist/fonts/*.woff2 and dist/the-lab-sans.css`)
